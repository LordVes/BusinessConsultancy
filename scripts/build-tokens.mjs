// Generates assets/css/tokens.css from tokens/tokens.json.
// tokens.json is the single source of truth (same structure as Figma Variables):
//   primitives -> raw palette, resolved but never emitted
//   light/dark -> modes of the semantic collection, emitted as CSS custom properties
//   scale      -> mode-independent values (space, radius, type, motion)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(resolve(root, "tokens/tokens.json"), "utf8"));

const lookup = (path) => path.split(".").reduce((node, key) => node?.[key], tokens);

function resolveValue(value) {
  return value.replace(/\{([^}]+)\}/g, (_, ref) => {
    const target = lookup(ref);
    if (!target || target.$value === undefined) throw new Error(`Unresolved token reference: {${ref}}`);
    return resolveValue(target.$value);
  });
}

function flatten(node, prefix = []) {
  const out = [];
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (child && typeof child === "object" && "$value" in child) {
      out.push([`--${[...prefix, key].join("-")}`, resolveValue(child.$value)]);
    } else if (child && typeof child === "object") {
      out.push(...flatten(child, [...prefix, key]));
    }
  }
  return out;
}

const block = (selector, vars, extra = "") =>
  `${selector} {\n${vars.map(([k, v]) => `  ${k}: ${v};`).join("\n")}${extra}\n}`;

const scale = flatten(tokens.scale);
const light = flatten(tokens.light);
const dark = flatten(tokens.dark);

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */

${block(":root", [...scale, ...light], "\n  color-scheme: light;")}

@media (prefers-color-scheme: dark) {
${block(':root:not([data-theme="light"])', dark, "\n  color-scheme: dark;").replace(/^/gm, "  ")}
}

${block(':root[data-theme="dark"]', dark, "\n  color-scheme: dark;")}
`;

writeFileSync(resolve(root, "assets/css/tokens.css"), css);
console.log(`tokens.css written: ${scale.length} scale, ${light.length} semantic tokens x 2 modes`);
